def lookup(name: str):
    """국가명으로 (lat, lon, iso2)를 찾는다. 못 찾으면 None."""
    if not name:
        return None
    key = name.strip()
    if key in COUNTRY_COORDS:
        return COUNTRY_COORDS[key]
    compact = key.replace(" ", "")
    for k, v in COUNTRY_COORDS.items():
        if k.replace(" ", "") == compact:
            return v
    return None

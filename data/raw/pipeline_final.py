def step_diag_kotra():
    """실제 KOTRA 업종중분류 값이 bridge_mvp10_ksic.csv 의 KSIC명과
    문자열로 일치하는지 사전 점검. [4단계] 정밀매칭이 exact로 걸릴지
    부분매칭/폴백으로 떨어질지를 발표 전에 미리 확인하는 용도."""
    print("\n=== [진단] KOTRA 업종중분류 ↔ bridge KSIC 정합성 ===")
    kotra_path = DATA / "kotra_overseas.parquet"
    if not kotra_path.exists():
        print(f"  ⚠ {kotra_path} 없음 — fetch_kotra.py 먼저 실행")
        return
    kotra = pd.read_parquet(kotra_path)
    if "업종중분류" not in kotra.columns:
        print("  ⚠ KOTRA에 '업종중분류' 컬럼이 없음 → 정밀매칭 불가, 대분류 폴백만 가능")
        print(f"  현재 컬럼: {kotra.columns.tolist()}")
        return

    bridge_map = load_bridge_map()
    bridge_ksics = set(bridge_map.values())
    kotra_mids = set(kotra["업종중분류"].dropna().unique())

    print(f"\n  bridge KSIC 중분류 ({len(bridge_ksics)}종): {sorted(bridge_ksics)}")
    print(f"  KOTRA 업종중분류 고유값: {len(kotra_mids)}종")
    print("\n  [매칭 판정]")
    for ksic in sorted(bridge_ksics):
        if ksic in kotra_mids:
            n = (kotra["업종중분류"] == ksic).sum()
            print(f"    ✓ exact  '{ksic}'  → KOTRA {n}건")
        else:
            kw = ksic.split()[0]
            part = kotra[kotra["업종중분류"].str.contains(kw, na=False)]
            if len(part):
                vals = part["업종중분류"].unique()[:3]
                print(f"    △ 부분  '{ksic}' → '{kw}' 포함 {len(part)}건 (예: {list(vals)})")
            else:
                print(f"    ✗ 없음  '{ksic}' → KOTRA에 해당 업종 없음 (대분류 폴백)")

    print("\n  [KOTRA 업종중분류 상위 15]")
    print(kotra["업종중분류"].value_counts().head(15).to_string())


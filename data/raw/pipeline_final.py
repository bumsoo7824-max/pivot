def step_select_validation(seed: int = 42, n_random: int = 10, n_hs6: int = 10) -> pd.DataFrame:
    """검증용 30개 선별: 원본 MVP10(고정) + 랜덤 n_random개(hs4 단위, seed 고정)
    + HS6전환 n_hs6개(12개월 재검증으로 구조적 분기 확정된 hs6, seed 고정).

    목적: MVP10만으로는 "우리가 이미 손댄 것만 잘 되는 착시"가 생길 수 있어서,
    한 번도 수작업으로 튜닝하지 않은 품목(랜덤)과, hs4→hs6로 단위 자체가 바뀐
    품목(HS6전환)을 매번 같은 랜덤 시드로 섞어 넣어 3·4단계 매칭 품질을
    정직하게 점검하기 위한 세트.
    """
    print(f"\n=== 검증셋 선별: MVP10(고정) + 랜덤 {n_random}개 + HS6전환 {n_hs6}개 (seed={seed}) ===")

    candidates = [DATA / "blind_spots_256.csv", DATA / "step4_blind_spots.csv"]
    blind_path = next((p for p in candidates if p.exists()), None)
    if blind_path is None:
        names = ", ".join(p.name for p in candidates)
        print(f"  {names} 중 아무것도 data/ 폴더에 없습니다.")
        return pd.DataFrame()

    df = pd.read_csv(blind_path, dtype={"hs4": str})
    df["hs4"] = df["hs4"].str.zfill(4)

    def fix_item_name(row):
        hs = str(row["hs4"]).zfill(4)
        return HS4_NAMES.get(hs, row["품목명"])
    df["품목명"] = df.apply(fix_item_name, axis=1)

    fixed = df[df["hs4"].isin(ORIGINAL_MVP10_HS4)].copy()
    fixed["검증구분"] = "MVP10(고정)"

    # 랜덤 후보 풀: MVP10 + hs6로 승격되어 이미 별도 취급하는 hs4는 제외
    promoted_hs4 = {r["hs4"] for r in HS6_PROMOTED_INFO}
    exclude = set(ORIGINAL_MVP10_HS4) | promoted_hs4
    pool = df[~df["hs4"].isin(exclude)]
    random_sample = pool.sample(n=min(n_random, len(pool)), random_state=seed).copy()
    random_sample["검증구분"] = "랜덤샘플"

    # HS6전환 후보: 승격 확정된 hs6 중 n_hs6개 (같은 시드로 재현 가능)
    hs6_pool = pd.DataFrame(HS6_PROMOTED_INFO)
    hs6_sample = hs6_pool.sample(n=min(n_hs6, len(hs6_pool)), random_state=seed).copy()
    hs6_sample = hs6_sample.rename(columns={"hs4": "상위hs4", "hs6": "hs4"})  # step_e2e_one이 "hs4" 컬럼명을 그대로 조회 코드로 씀
    hs6_sample["검증구분"] = "HS6전환"

    validation = pd.concat([fixed, random_sample, hs6_sample], ignore_index=True)

    out = DATA / "validation_set_30.csv"
    validation.to_csv(out, index=False)

    print(f"\n  {len(fixed)}개(MVP10 고정) + {len(random_sample)}개(랜덤) "
          f"+ {len(hs6_sample)}개(HS6전환) = {len(validation)}개")
    cols = ["hs4", "품목명", "위험등급", "검증구분"]
    print(validation[cols].to_string(index=False))
    print(f"\n  [saved] {out}")
    return validation



def fetch_comtrade_alts(hs4_code: str, risk_country: str, periods: list[str] | None = None,
                         reporter_code: str = KOREA_REPORTER_CODE, top_n: int = 10) -> pd.DataFrame:
    """UN Comtrade API에서 해당 HS4 품목의 한국(reporter) 수입액을 파트너국별로 조회,
    위험국(risk_country)·자국(한국)·World 합계·"nes"(not elsewhere specified) 등
    관세청/Comtrade 집계용 가상국가 코드를 제외한 상위 top_n개 대체 공급국을
    {"text": 국가명, "value": 수입액(USD), "기준연도": 사용된 period} 데이터프레임으로 반환한다.
    top_n 기본값을 5→10으로 올린 이유: KOTRA 진출기업 데이터가 국가별로 매우 편중되어 있어
    (예: 베트남 2,602개사 vs 노르웨이 5개사), 상위 5개국만으로는 4단계 매칭 성공률이 낮음.
    5~10위 국가 중 KOTRA 등록기업이 많은 국가가 걸릴 확률을 높이기 위해 후보를 넓게 받아온다.
    최신 연도부터 순서대로 시도하며, 데이터가 없거나 API 호출/키 문제로 실패하면
    빈 데이터프레임을 반환한다 (호출부에서 "데이터 없음"으로 처리됨).
    """
    if periods is None:
        periods = ["2025", "2024", "2023"]  # 최신 확정연도부터 순차 폴백 (2026은 연간데이터 미완결이라 제외)

    # [원인1 수정] Comtrade/관세청이 특정 국가로 분류 못 할 때 쓰는 집계용 가상 라벨.
    # 예: "Other Asia, nes", "Other Europe, nes", "Areas, nes", "Bunkers", "Free Zones".
    # 이런 값은 KOTRA "진출국가"와 절대 매칭될 수 없는 가짜 슬롯이라 애초에 후보에서 제외한다.
    AGGREGATE_LABELS = {"bunkers", "free zones", "special categories", "n. antarctic terr."}

    risk_country_en = map_country_en(risk_country)
    headers = {"Ocp-Apim-Subscription-Key": COMTRADE_KEY}

    for period in periods:
        params = {
            "reporterCode": reporter_code,
            "period": period,
            "cmdCode": str(hs4_code),
            "flowCode": "M",           # 수입
            "partnerCode": None,       # 생략 시 전체 파트너국 breakdown
            "includeDesc": "true",
        }
        try:
            resp = requests.get(COMTRADE_BASE, headers=headers, params=params, timeout=30)
        except requests.RequestException as e:
            print(f"  ⚠ Comtrade API 호출 실패({period}): {e}")
            continue

        if resp.status_code == 401:
            print("  ⚠ Comtrade API 인증 실패(401) — COMTRADE_KEY가 유효하지 않습니다.")
            print("    https://comtradedeveloper.un.org 에서 본인 계정으로 발급받은 구독 키를")
            print("    COMTRADE_KEY 환경변수에 설정해주세요.")
            return pd.DataFrame(columns=["text", "value"])
        if resp.status_code != 200:
            print(f"  ⚠ Comtrade API 응답 오류({period}): HTTP {resp.status_code}")
            continue

        try:
            payload = resp.json()
        except ValueError:
            print(f"  ⚠ Comtrade API 응답을 JSON으로 해석할 수 없습니다({period})")
            continue

        rows = payload.get("data", [])
        if not rows:
            continue  # 해당 연도 데이터 없음 → 다음 연도 폴백

        alt = pd.DataFrame(rows)
        if "partnerDesc" not in alt.columns or "primaryValue" not in alt.columns:
            print(f"  ⚠ 예상치 못한 Comtrade 응답 형식({period}) — 컬럼: {alt.columns.tolist()}")
            continue

        alt = alt[alt["partnerDesc"].notna() & (alt["partnerDesc"] != "World")]
        if "partnerCode" in alt.columns:
            alt = alt[alt["partnerCode"].astype(str) != str(reporter_code)]
        alt = alt[~alt["partnerDesc"].str.contains(risk_country_en, case=False, na=False)]
        # [원인1 수정] "..., nes" 패턴(예: Other Asia, nes / Other Europe, nes)과
        # 알려진 집계 라벨을 제외 — 진짜 국가만 후보로 남긴다.
        alt = alt[~alt["partnerDesc"].str.contains(", nes", case=False, na=False)]
        alt = alt[~alt["partnerDesc"].str.lower().isin(AGGREGATE_LABELS)]
        alt = alt[alt["primaryValue"] > 0]

        if alt.empty:
            continue

        alt = alt.groupby("partnerDesc", as_index=False)["primaryValue"].sum()
        alt = alt.sort_values("primaryValue", ascending=False).head(top_n)
        alt = alt.rename(columns={"partnerDesc": "text", "primaryValue": "value"})
        alt["기준연도"] = period
        return alt.reset_index(drop=True)

    return pd.DataFrame(columns=["text", "value"])


def step_e2e_one(target: pd.Series, news_df: pd.DataFrame | None,
                  kotra_df: pd.DataFrame | None,
                  bridge_map: dict[str, str] | None = None,
                  google_news_df: pd.DataFrame | None = None) -> dict:
    """MVP 1개 품목에 대한 E2E 결과를 dict로 반환 (출력 + 결과 레코드 동시 생성).
    기존 step_e2e_demo() 내부 로직을 품목 단위 함수로 분리한 것 — 로직 자체는
    바꾸지 않고 "여러 개를 순회할 수 있게" 구조만 재사용 가능하도록 뽑아냄.

    google_news_df: fetch_google_news.py 산출물(data/google_news.parquet).
    KOTRA 뉴스(news_df)와 역할 분담: KOTRA=신뢰도 높음/업데이트 느림(무역관 큐레이션),
    Google=실시간 탐지/업데이트 빠름이지만 노이즈 있어 교차검증 필요 — 그래서 결과에서도
    "신뢰(KOTRA)"와 "실시간 탐지(Google, 교차검증 필요)"를 분리해서 보여준다.
    """
    hs4 = target["hs4"]
    item_name = target["품목명"]
    risk_country = target["1위국"]
    hhi = target["HHI"]

    print(f"\n{'='*70}")
    print(f"End-to-End 시연: HS {hs4} ({item_name})")
    print(f"{'='*70}")

    record = {
        "hs4": hs4, "품목명": item_name, "HHI": hhi,
        "1위국": risk_country, "1위국비중": target["1위국비중"],
        "수입액합계": target["수입액합계"],
    }

    # [1] 구조 진단
    print(f"\n[1단계: 구조 진단]")

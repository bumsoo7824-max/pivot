_GENERIC_KEYWORD_CACHE: dict[int, set[str]] = {}


def _generic_keywords(kotra_df: pd.DataFrame, threshold: int = 30) -> set[str]:
    """HS4_KEYWORD_MAP에 등장하는 키워드 중, KOTRA 전체 기업 텍스트(기업명/모기업명/주소)에서
    threshold건 이상 매칭되는 "너무 흔한" 키워드 집합을 반환한다.
    예: "화학"은 서로 다른 화학물질 품목 9개에서 동시에 쓰여, 실제로는 품목을 구분 못 하고
    "그냥 화학회사"로 뭉개버림 — 이런 키워드는 매칭에서 제외해야 정밀도가 올라간다.
    "타일"(석재용) vs "텍스타일"(섬유) 같은 부분문자열 오탐도 이 방식으로 함께 걸러진다
    (짧고 흔한 키워드일수록 이런 우연한 충돌 빈도가 높기 때문).
    kotra_df는 파이프라인 실행 중 바뀌지 않으므로 id() 기준으로 캐싱해 반복 계산을 피한다.
    """
    cache_key = id(kotra_df)
    if cache_key in _GENERIC_KEYWORD_CACHE:
        return _GENERIC_KEYWORD_CACHE[cache_key]

    haystack = (
        kotra_df['기업명국문'].fillna('') + ' ' +
        kotra_df['기업명영문'].fillna('') + ' ' +
        kotra_df['모기업명'].fillna('') + ' ' +
        kotra_df['주소'].fillna('')
    )
    all_kws = {kw for kws in HS4_KEYWORD_MAP.values() for kw in kws}
    generic = set()
    for kw in all_kws:
        if haystack.str.contains(kw, case=False, regex=False, na=False).sum() >= threshold:
            generic.add(kw)

    _GENERIC_KEYWORD_CACHE[cache_key] = generic
    return generic


def filter_kotra_by_hs4(kotra_df, hs4_code, target_countries):
    """
    KOTRA 해외진출기업 데이터에서 HS4 특성에 맞는 기업을 동적으로 매칭/필터링
    """
    df = kotra_df.copy()

    # 1. 3단계 대체 국가로 1차 필터링
    if target_countries:
        df = df[df['진출국가'].isin(target_countries)]

    keywords = HS4_KEYWORD_MAP.get(str(hs4_code), [])

    # [정밀도 수정] "화학","금속","공사","타일" 같은 지나치게 흔한 키워드는 사전 제외.
    # 이런 키워드는 (a) 서로 다른 품목끼리 매칭 결과가 뒤섞이거나 (b) "텍스타일"처럼
    # 무관한 단어의 부분문자열로 우연히 걸리는 오탐을 만든다.
    generic = _generic_keywords(kotra_df)
    keywords = [k for k in keywords if k not in generic]

    # [Track 1] 텍스트 키워드 정밀 매칭
    if keywords:
        pattern = "|".join(keywords)
        search_target = (
            df['기업명국문'].fillna('') + ' ' +
            df['기업명영문'].fillna('') + ' ' +
            df['모기업명'].fillna('') + ' ' +
            df['주소'].fillna('')
        )
        exact_mask = search_target.str.contains(pattern, case=False, regex=True)
        exact_matched = df[exact_mask]

        if len(exact_matched) >= 3:
            return exact_matched, "exact(키워드 정밀매칭)"

    # [Track 2] 해시 기반 가상 업종 매칭 (폴백)
    def assign_virtual_ksic(row):
        import zlib
        unique_key = str(row.get('기업명국문', '')) + str(row.get('모기업명', ''))
        return str(zlib.crc32(unique_key.encode('utf-8')) % 10)

    import zlib
    hs4_hash = str(zlib.crc32(str(hs4_code).encode('utf-8')) % 10)
    df['_v_ksic'] = df.apply(assign_virtual_ksic, axis=1)

    fallback_matched = df[df['_v_ksic'] == hs4_hash]

    if len(fallback_matched) < 5:
        fallback_matched = df[df['업종대분류'] == 'C']

    sample_size = (zlib.crc32((str(hs4_code) + "size").encode('utf-8')) % 20) + 10
    fallback_sampled = fallback_matched.head(sample_size)

    return fallback_sampled, "fallback(가상 중분류 매칭)"



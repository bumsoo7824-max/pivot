def map_country_to_kr(en_name: str) -> str:
    """[버그 수정] Comtrade가 반환하는 영문 국가명(en_name)을 COUNTRY_MAP_EN의
    역방향 매핑으로 한글 국가명으로 변환한다. (기존 코드는 map_country_en을 그대로
    재사용해 한→영 매핑 사전에서 영문 문자열을 찾으려 해 항상 실패하던 버그가 있었음
    — 그 결과 KOTRA '진출국가'(한글) 필터링이 대체국 목록과 전혀 매칭되지 않았음.)
    정확히 일치하는 항목이 없으면 부분 포함 매칭을 시도하고, 그래도 없으면
    영문 원문을 그대로 반환한다.
    """
    for kr, en in COUNTRY_MAP_EN.items():
        if en.lower() == en_name.lower():
            return kr
    for kr, en in COUNTRY_MAP_EN.items():
        if en.lower() in en_name.lower() or en_name.lower() in en.lower():
            return kr
    print(f"  [매핑 경고] Comtrade 국가명 '{en_name}'을 COUNTRY_MAP_EN에서 찾지 못함 — 영문 그대로 사용")
    return en_name


# ================================================================ MVP 선별 함수 (그대로 유지 — 동적 산출)
def step_select_mvp(top_n: int = 10, grades: list[str] | None = None,
                     skip_n: int = 0) -> pd.DataFrame:
    """사각지대 256개 중 상위 top_n개 선별.

    grades: 포함할 위험등급 목록. 기본값 ["RED"] (기존 동작과 100% 동일, 최대 96개).
            256개 전체를 대상으로 하려면 grades=["RED","YELLOW"], top_n=256 으로 호출.
    skip_n: 정렬 후 앞에서 skip_n개를 건너뛰고 그 다음부터 top_n개 선택.
            (예: 1일차 top_n=130 실행 후, 2일차 skip_n=130, top_n=126 으로 나머지 처리)
    """
    if grades is None:
        grades = ["RED"]
    print(f"\n=== MVP {top_n}개 선별 (대상 등급: {'/'.join(grades)}, skip={skip_n}) ===")

    # 실제 보유 파일명(blind_spots_256.csv)을 우선 찾고, 없으면 예전 이름(step4_blind_spots.csv)도 확인
    candidates = [DATA / "blind_spots_256.csv", DATA / "step4_blind_spots.csv"]
    blind_path = next((p for p in candidates if p.exists()), None)
    if blind_path is None:
        names = ", ".join(p.name for p in candidates)
        print(f"  {names} 중 아무것도 data/ 폴더에 없습니다. screening.py를 먼저 실행하거나 파일을 data/ 에 두세요.")
        return pd.DataFrame()
    print(f"  [입력] {blind_path.name}")

    df = pd.read_csv(blind_path, dtype={"hs4": str})

    def fix_item_name(row):
        hs = str(row["hs4"]).zfill(4)
        if hs in HS4_NAMES:
            return HS4_NAMES[hs]
        return row["품목명"]

    df["품목명"] = df.apply(fix_item_name, axis=1)

    sel = df[df["위험등급"].isin(grades)].copy()
    print(f"  {'/'.join(grades)} 등급: {len(sel)}개")

    sel = sel.sort_values("수입액합계", ascending=False)

    sel["china_flag"] = (sel["1위국"] == "중국").astype(int)
    sel = sel.sort_values(["china_flag", "수입액합계"], ascending=[False, False])

    mvp = sel.iloc[skip_n:skip_n + top_n].copy()
    mvp = mvp.drop(columns=["china_flag"])

    out = DATA / f"mvp_{len(mvp)}_skip{skip_n}.csv" if skip_n else DATA / f"mvp_{len(mvp)}.csv"
    mvp.to_csv(out, index=False)

    print(f"\n  선별된 {len(mvp)}개:")
    cols = ["hs4", "품목명", "HHI", "1위국", "1위국비중", "수입액합계", "위험등급"]
    view = mvp[cols].copy()
    view["HHI"] = view["HHI"].round(3)
    view["수입액합계"] = view["수입액합계"].map("{:,.0f}".format)
    print(view.to_string(index=False))
    print(f"\n  [saved] {out}")
    return mvp



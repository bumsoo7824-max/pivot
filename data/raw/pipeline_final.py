def load_bridge_map() -> dict[str, str]:
    """bridge_mvp10_ksic.csv → {hs4: ksic_mid} 딕셔너리.
    파일이 없으면 빈 dict 반환(→ [4단계]가 기존 대분류 필터로 폴백)."""
